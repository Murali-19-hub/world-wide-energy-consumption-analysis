-- Data Analysis Questions

--  General & Comparative Analysis

-- What is the total emission per country for the most recent year available?
SELECT COUNTRY,SUM(EMISSION) TOTAL_EMISSION FROM EMISSION_3
WHERE YEAR=(SELECT MAX(YEAR) FROM EMISSION_3)
GROUP BY COUNTRY;

-- What are the top 5 countries by GDP in the most recent year?
SELECT COUNTRY,VALUE GDP FROM GDP_3
WHERE YEAR=(SELECT MAX(YEAR) FROM GDP_3)
ORDER BY GDP DESC
LIMIT 5;


-- Compare energy production and consumption by country and year. 
SELECT P.COUNTRY,P.ENERGY,P.YEAR,P.PRODUCTION,C.CONSUMPTION
FROM PRODUCTION P JOIN CONSUMPTION C
ON P.COUNTRY=C.COUNTRY
AND P.YEAR=C.YEAR
AND P.ENERGY=C.ENERGY;

-- Which energy types contribute most to emissions across all countries?
SELECT ENERGY_TYPE,TOTAL_EMISSIONS,
DENSE_RANK() OVER (ORDER BY TOTAL_EMISSIONS DESC) EMISSION_RANK FROM
(SELECT ENERGY_TYPE,SUM(EMISSION) AS TOTAL_EMISSIONS FROM EMISSION_3 GROUP BY ENERGY_TYPE) X;

-- Trend Analysis Over Time

-- How have global emissions changed year over year?
SELECT YEAR,TOTAL_EMISSION,PREVIOUS_YEAR_EMISSION,
TOTAL_EMISSION-PREVIOUS_YEAR_EMISSION YOY_CHANGE
FROM (
SELECT YEAR,TOTAL_EMISSION,
LAG(TOTAL_EMISSION) OVER (ORDER BY YEAR) PREVIOUS_YEAR_EMISSION 
FROM (
SELECT YEAR,SUM(EMISSION) TOTAL_EMISSION FROM EMISSION_3
GROUP BY YEAR 
) X
) Y;

-- What is the trend in GDP for each country over the given years?
SELECT COUNTRY,YEAR,VALUE,
LAG(VALUE) OVER (partition by COUNTRY ORDER BY YEAR) PREVIOUS_YEAR_GDP
FROM GDP_3; 

-- How has population growth affected total emissions in each country?
SELECT P.COUNTRIES, P.VALUE POPULATION ,P.YEAR,SUM(E.EMISSION) TOTAL_EMISSION FROM 
POPULATION P JOIN EMISSION_3 E ON P.COUNTRIES=E.COUNTRY AND P.YEAR=E.YEAR
GROUP BY P.COUNTRIES,P.YEAR,P.VALUE
ORDER BY P.COUNTRIES,P.YEAR;

-- Has energy consumption increased or decreased over the years for major economies?
SELECT COUNTRY,YEAR,TOTAL_CONSUMPTION,
LAG(TOTAL_CONSUMPTION) OVER(PARTITION BY COUNTRY ORDER BY YEAR) PREVIOUS_YEAR_CONSUMPTION
FROM(
SELECT C.COUNTRY,
       C.YEAR,
       SUM(C.CONSUMPTION) AS TOTAL_CONSUMPTION
FROM CONSUMPTION C
JOIN
(
    SELECT G.COUNTRY
    FROM GDP_3 G
    WHERE G.YEAR = (SELECT MAX(YEAR) FROM GDP_3)
    ORDER BY G.VALUE DESC
    LIMIT 5
) G
ON C.COUNTRY = G.COUNTRY
GROUP BY C.COUNTRY, C.YEAR
)X;

-- What is the average yearly change in emissions per capita for each country?
SELECT E.COUNTRY,E.YEAR,SUM(EMISSION)/P.VALUE AS EMISSION_PER_CAPITA
FROM EMISSION_3 E 
JOIN POPULATION P
	ON E.COUNTRY=P.COUNTRIES
    AND E.YEAR=P.YEAR
GROUP BY E.COUNTRY,E.YEAR,P.VALUE
ORDER BY E.COUNTRY,E.YEAR


-- Ratio & Per Capita Analysis
-- What is the emission-to-GDP ratio for each country by year?

WITH TOTAL_EMISSIONS AS
(
	SELECT COUNTRY,YEAR,SUM(EMISSION) AS TOTAL_EMISSION
    FROM EMISSION_3
    GROUP BY COUNTRY,YEAR
)
SELECT E.COUNTRY,
	   E.YEAR,
       E.TOTAL_EMISSION,
       G.VALUE AS GDP,
       E.TOTAL_EMISSION/G.VALUE AS EMISSION_GDP_RATIO
FROM TOTAL_EMISSIONS E 
JOIN GDP_3 G
ON E.COUNTRY=G.COUNTRY
AND E.YEAR=G.YEAR
ORDER BY E.COUNTRY,E.YEAR;


-- What is the energy consumption per capita for each country over the last decade?
SELECT C.COUNTRY,C.YEAR,SUM(C.CONSUMPTION) AS TOTAL_CONSUMPTION,P.VALUE AS POPULATION,
SUM(C.CONSUMPTION)/P.VALUE AS ENERGY_CONSUMPTION_PER_CAPITA
FROM CONSUMPTION C JOIN POPULATION P
ON C.COUNTRY=P.COUNTRIES
AND C.YEAR=P.YEAR
GROUP BY C.COUNTRY,C.YEAR,P.VALUE
ORDER BY C.COUNTRY,C.YEAR;

-- How does energy production per capita vary across countries?
SELECT PR.COUNTRY,PR.YEAR,SUM(PR.PRODUCTION) AS TOTAL_PRODUCTION,P.VALUE AS POPULATION,
SUM(PR.PRODUCTION)/P.VALUE AS ENERGY_PRODUCTION_PER_CAPITA 
FROM PRODUCTION PR JOIN POPULATION P 
ON PR.COUNTRY=P.COUNTRIES
AND PR.YEAR=P.YEAR
GROUP BY PR.COUNTRY,PR.YEAR,P.VALUE
ORDER BY PR.COUNTRY,PR.YEAR;

-- Which countries have the highest energy consumption relative to GDP?
WITH ENERGY_CONSUMPTION AS
(
SELECT C.COUNTRY,
C.YEAR,
SUM(C.CONSUMPTION) AS TOTAL_CONSUMPTION,
 G.VALUE AS GDP 
 FROM CONSUMPTION C JOIN GDP_3 G
 ON C.COUNTRY=G.COUNTRY
 AND C.YEAR=G.YEAR
 GROUP BY C.COUNTRY,C.YEAR,G.VALUE
 )
 SELECT COUNTRY,
		TOTAL_CONSUMPTION,
        GDP,
        TOTAL_CONSUMPTION/GDP AS CONSUMPTION_GDP_RATIO
FROM ENERGY_CONSUMPTION
ORDER BY CONSUMPTION_GDP_RATIO DESC;

--  Global Comparisons

-- What are the top 10 countries by population and how do their emissions compare?
WITH TOP_10_COUNTRIES AS
(
    SELECT COUNTRIES
    FROM POPULATION
    WHERE YEAR = 2023
    ORDER BY VALUE DESC
    LIMIT 10
)

SELECT P.COUNTRIES,
       P.VALUE AS POPULATION,
       SUM(E.EMISSION) AS TOTAL_EMISSION
FROM POPULATION P
JOIN TOP_10_COUNTRIES T
    ON P.COUNTRIES = T.COUNTRIES
JOIN EMISSION_3 E
    ON P.COUNTRIES = E.COUNTRY
    AND P.YEAR = E.YEAR
WHERE P.YEAR = 2023
GROUP BY P.COUNTRIES, P.VALUE
ORDER BY POPULATION DESC;

-- Which countries have improved (reduced) their per capita emissions the most over the last decade?
WITH yearly AS
(
    SELECT COUNTRY,
           YEAR,
           MAX(PER_CAPITA_EMISSION) AS PER_CAPITA_EMISSION
    FROM EMISSION_3
    GROUP BY COUNTRY, YEAR
)
SELECT A.COUNTRY,
       A.PER_CAPITA_EMISSION AS EMISSION_2020,
       B.PER_CAPITA_EMISSION AS EMISSION_2023,
       A.PER_CAPITA_EMISSION - B.PER_CAPITA_EMISSION AS REDUCTION
FROM yearly A
JOIN yearly B
    ON A.COUNTRY = B.COUNTRY
WHERE A.YEAR = 2020
  AND B.YEAR = 2023
ORDER BY REDUCTION DESC;


-- What is the global share (%) of emissions by country?
SELECT COUNTRY,
       SUM(EMISSION) AS TOTAL_EMISSION,
       SUM(EMISSION) /
       (SELECT SUM(EMISSION)
        FROM EMISSION_3) * 100 AS GLOBAL_SHARE
FROM EMISSION_3
GROUP BY COUNTRY
ORDER BY GLOBAL_SHARE DESC;

-- What is the global average GDP, emission, and population by year?
SELECT G.YEAR,AVG(G.VALUE) AS AVG_GDP,AVG(E.TOTAL_EMISSION) AS AVG_EMISSION,AVG(P.VALUE) AS AVG_POPULATION
FROM GDP_3 G
JOIN (SELECT COUNTRY,YEAR,SUM(EMISSION) AS TOTAL_EMISSION
    FROM EMISSION_3
    GROUP BY COUNTRY, YEAR
) E ON G.COUNTRY = E.COUNTRY AND G.YEAR = E.YEAR
JOIN POPULATION P ON G.COUNTRY = P.COUNTRIES AND G.YEAR = P.YEAR
GROUP BY G.YEAR
ORDER BY G.YEAR;
